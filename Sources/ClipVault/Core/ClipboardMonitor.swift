import AppKit
import CryptoKit

@MainActor
final class ClipboardMonitor {
    private let db: Database
    private let blobStore: BlobStore
    private let settings = Settings.shared
    private var lastChangeCount: Int
    private var timer: Timer?
    private var ignoreNextChange = false
    var onNewItem: (() -> Void)?

    init(db: Database, blobStore: BlobStore) {
        self.db = db
        self.blobStore = blobStore
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        // Polling is the standard, App-Store-safe way to observe pasteboard changes —
        // macOS provides no push notification for NSPasteboard.general.
        timer = Timer.scheduledTimer(withTimeInterval: 0.2, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated {
                self?.checkPasteboard()
            }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Call right before we programmatically write to the pasteboard (e.g. to paste a
    /// history item back out) so we don't re-capture our own write as a new item.
    func suppressNextChange() {
        ignoreNextChange = true
    }

    private func checkPasteboard() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount

        if ignoreNextChange {
            ignoreNextChange = false
            return
        }

        if settings.ignorePasswordManagers {
            let concealedTypes: Set<String> = [
                "org.nspasteboard.ConcealedType",
                "org.nspasteboard.TransientType",
                "org.nspasteboard.AutoGeneratedType"
            ]
            let pbTypeNames = Set((pb.types ?? []).map { $0.rawValue })
            if !pbTypeNames.isDisjoint(with: concealedTypes) {
                return
            }
        }

        let frontApp = NSWorkspace.shared.frontmostApplication
        let bundleID = frontApp?.bundleIdentifier
        if let bundleID, settings.excludedBundleIDs.contains(bundleID) {
            return
        }
        let appName = frontApp?.localizedName

        capture(from: pb, bundleID: bundleID, appName: appName)
    }

    private func capture(from pb: NSPasteboard, bundleID: String?, appName: String?) {
        let now = Date()

        // Prefer richer types first: image > file list > rtf > plain text.
        if let fileURLs = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !fileURLs.isEmpty {
            let joined = fileURLs.map { $0.path }.joined(separator: "\n")
            insertIfNew(kind: .fileList, previewText: fileURLs.map { $0.lastPathComponent }.joined(separator: ", "),
                        fullText: joined, data: Data(joined.utf8), ext: "txt",
                        bundleID: bundleID, appName: appName, createdAt: now, pixelSize: nil)
            return
        }

        if let imageData = pb.data(forType: .tiff) ?? pb.data(forType: .png),
           let image = NSImage(data: imageData) {
            let pngData = Self.pngData(from: image) ?? imageData
            let size = image.size
            insertIfNew(kind: .image, previewText: "Image", fullText: nil, data: pngData, ext: "png",
                        bundleID: bundleID, appName: appName, createdAt: now,
                        pixelSize: (Int(size.width), Int(size.height)))
            return
        }

        if let rtfData = pb.data(forType: .rtf) {
            let plain = pb.string(forType: .string) ?? ""
            insertIfNew(kind: .rtf, previewText: String(plain.prefix(400)), fullText: plain,
                        data: rtfData, ext: "rtf", bundleID: bundleID, appName: appName,
                        createdAt: now, pixelSize: nil)
            return
        }

        if let text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let kind: ClipKind = (URL(string: text)?.scheme != nil && !text.contains(" ") && !text.contains("\n")) ? .url : .text
            insertIfNew(kind: kind, previewText: String(text.prefix(400)), fullText: text,
                        data: nil, ext: nil, bundleID: bundleID, appName: appName,
                        createdAt: now, pixelSize: nil)
            return
        }
    }

    private func insertIfNew(kind: ClipKind, previewText: String, fullText: String?, data: Data?, ext: String?,
                              bundleID: String?, appName: String?, createdAt: Date, pixelSize: (Int, Int)?) {
        let hashInput = fullText ?? data?.base64EncodedString() ?? previewText
        let hash = Self.sha256(hashInput + kind.rawValue)

        // Dedupe consecutive identical copies (very common: copy, glance elsewhere, copy again).
        if db.mostRecentHash() == hash { return }

        var blobPath: String?
        var byteSize = fullText?.utf8.count ?? 0
        if let data, let ext {
            let (path, _) = blobStore.write(data, ext: ext)
            blobPath = path
            byteSize = data.count
        }

        let id = db.insert(kind: kind, previewText: previewText, fullText: fullText, blobPath: blobPath,
                            sourceApp: bundleID, sourceAppName: appName, createdAt: createdAt,
                            pixelWidth: pixelSize?.0 ?? 0, pixelHeight: pixelSize?.1 ?? 0,
                            byteSize: byteSize, contentHash: hash)
        if id > 0 {
            enforceRetentionLimits()
            onNewItem?()
        }
    }

    private func enforceRetentionLimits() {
        if settings.maxHistoryCount > 0 {
            let stale = db.trimHistory(keepCount: settings.maxHistoryCount)
            stale.forEach { blobStore.delete(relativePath: $0) }
        }
        let maxBytes = Int64(settings.maxDiskMegabytes) * 1_048_576
        if maxBytes > 0 {
            var currentSize = blobStore.totalSizeOnDisk()
            var keepCount = db.totalCount()
            while currentSize > maxBytes && keepCount > 1 {
                keepCount = max(1, keepCount - 50)
                let stale = db.trimHistory(keepCount: keepCount)
                if stale.isEmpty { break }
                stale.forEach { blobStore.delete(relativePath: $0) }
                currentSize = blobStore.totalSizeOnDisk()
            }
        }
    }

    private static func sha256(_ string: String) -> String {
        let digest = SHA256.hash(data: Data(string.utf8))
        return digest.map { String(format: "%02x", $0) }.joined()
    }

    private static func pngData(from image: NSImage) -> Data? {
        guard let tiff = image.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}
