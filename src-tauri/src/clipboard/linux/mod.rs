pub fn create() -> Result<Box<dyn ClipboardBackend>> {
    if std::env::var_os("WAYLAND_DISPLAY").is_some() {
        if let Ok(backend) = wayland::Wayland::new() {
            return Ok(Box::new(backend));
        }
        if let Ok(backend) = gnome::Gnome::new() {
            return Ok(Box::new(backend));
        }
        return Ok(Box::new(Unavailable));
    }
    Ok(Box::new(x11::X11::new()?))
}
pub const MARKER: &str = "application/x-clipvault-local-write";
pub fn sensitive(types: &[String]) -> bool {
    types.iter().any(|t| {
        matches!(
            t.as_str(),
            "x-kde-passwordManagerHint"
                | "application/x-keepassxc-secret"
                | "org.nspasteboard.ConcealedType"
                | "org.nspasteboard.TransientType"
                | "org.nspasteboard.AutoGeneratedType"
        )
    })
}
pub fn formats(clip: &Clip) -> Result<Vec<(String, Vec<u8>)>> {
    clip.validate()?;
    let mut formats = vec![(MARKER.into(), b"ClipVault".to_vec())];
    match clip.kind {
        Kind::Image => formats.push(("image/png".into(), clip.data.clone())),
        Kind::Files => {
            let text = clip.text.as_deref().unwrap_or("");
            let urls = text
                .lines()
                .filter_map(|p| url::Url::from_file_path(p).ok())
                .map(|u| u.to_string())
                .collect::<Vec<_>>()
                .join("\r\n");
            formats.push(("text/uri-list".into(), urls.into_bytes()));
        }
        _ => {
            let bytes = clip.text.as_deref().unwrap_or("").as_bytes().to_vec();
            for mime in [
                "text/plain;charset=utf-8",
                "UTF8_STRING",
                "text/plain",
                "STRING",
            ] {
                formats.push((mime.into(), bytes.clone()));
            }
            if clip.kind == Kind::Rtf {
                formats.push(("text/rtf".into(), clip.data.clone()));
            }
        }
    }
    Ok(formats)
}
pub fn read_formats(
    types: &[String],
    mut read: impl FnMut(&str, usize) -> Result<Vec<u8>>,
) -> Result<Option<Clip>> {
    if sensitive(types) {
        let mut clip = Clip::text(String::new());
        clip.sensitive = true;
        return Ok(Some(clip));
    }
    if types.iter().any(|t| t == "text/uri-list") {
        let raw = String::from_utf8(read("text/uri-list", MAX_TEXT)?)?;
        let paths: Vec<_> = raw
            .lines()
            .filter(|s| !s.starts_with('#'))
            .filter_map(|s| url::Url::parse(s).ok()?.to_file_path().ok())
            .map(|p| p.to_string_lossy().into_owned())
            .collect();
        if !paths.is_empty() {
            let mut clip = Clip::text(paths.join("\n"));
            clip.kind = Kind::Files;
            return Ok(Some(clip));
        }
    }
    if types.iter().any(|t| t == "image/png") {
        let clip = Clip {
            kind: Kind::Image,
            text: None,
            data: read("image/png", MAX_IMAGE)?,
            source_app: None,
            source_name: None,
            sensitive: false,
        };
        clip.validate()?;
        return Ok(Some(clip));
    }
    for mime in [
        "text/plain;charset=utf-8",
        "UTF8_STRING",
        "text/plain",
        "STRING",
    ] {
        if types.iter().any(|t| t == mime) {
            let bytes = read(mime, MAX_TEXT)?;
            let mut clip = Clip::text(String::from_utf8(bytes)?);
            if types.iter().any(|t| t == "text/rtf") {
                clip.kind = Kind::Rtf;
                clip.data = read("text/rtf", MAX_IMAGE)?;
            }
            return Ok(Some(clip));
        }
    }
    Ok(None)
}
struct Unavailable;
impl ClipboardBackend for Unavailable {
    fn snapshot(&mut self) -> Result<Option<Snapshot>> {
        Ok(None)
    }
    fn write(&mut self, _: &Clip) -> Result<()> {
        bail!("Enable the ClipVault GNOME helper to access this desktop's clipboard")
    }
    fn paste(&mut self) -> Result<()> {
        bail!("Paste using your application's shortcut")
    }
    fn capabilities(&self) -> Capabilities {
        Capabilities{backend:"Wayland — setup required".into(),monitoring:false,images:false,app_exclusions:false,automatic_paste:false,helper_required:true,message:Some("This desktop does not expose clipboard-manager access. On GNOME, install and enable the bundled helper, then sign out and back in if requested.".into())}
    }
}
