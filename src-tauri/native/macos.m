static pid_t previous_app_pid = 0;
static long owned_generation = -1;

static char *json_string(id value) {
    NSData *data = [NSJSONSerialization dataWithJSONObject:value options:0 error:nil];
    if (!data) return NULL;
    return strdup([[NSString alloc] initWithData:data encoding:NSUTF8StringEncoding].UTF8String);
}
void cv_free(char *value) { free(value); }
char *cv_read(long previous) {
    @autoreleasepool {
        NSPasteboard *pb = NSPasteboard.generalPasteboard;
        NSRunningApplication *front = NSWorkspace.sharedWorkspace.frontmostApplication;
        if (front && front.processIdentifier != getpid()) previous_app_pid = front.processIdentifier;
        long generation = pb.changeCount;
        if (generation == previous) return NULL;
        NSMutableDictionary *snapshot = [@{@"generation": [NSString stringWithFormat:@"%ld", generation], @"clip": NSNull.null, @"owned": generation == owned_generation ? @YES : @NO} mutableCopy];
        if ([snapshot[@"owned"] boolValue]) return json_string(snapshot);
        BOOL sensitive = NO;
        for (NSString *type in @[@"org.nspasteboard.ConcealedType", @"org.nspasteboard.TransientType", @"org.nspasteboard.AutoGeneratedType"]) if ([pb.types containsObject:type]) sensitive = YES;
        NSRunningApplication *app = NSWorkspace.sharedWorkspace.frontmostApplication;
        NSMutableDictionary *clip = [@{@"kind": @"text", @"text": @"", @"data": @"", @"sensitive": @(sensitive), @"source_app": app.bundleIdentifier ?: (id)NSNull.null, @"source_name": app.localizedName ?: (id)NSNull.null} mutableCopy];
        // Do not retrieve password-manager payloads at all.
        if (sensitive) { snapshot[@"clip"] = clip; return json_string(snapshot); }
        NSArray<NSURL *> *files = [pb readObjectsForClasses:@[NSURL.class] options:@{NSPasteboardURLReadingFileURLsOnlyKey: @YES}];
        if (files.count) {
            NSMutableArray *paths = [NSMutableArray array]; for (NSURL *url in files) [paths addObject:url.path];
            clip[@"kind"] = @"fileList"; clip[@"text"] = [paths componentsJoinedByString:@"\n"];
        } else if ([pb.types containsObject:NSPasteboardTypePNG] || [pb.types containsObject:NSPasteboardTypeTIFF]) {
            NSData *data = [pb dataForType:NSPasteboardTypePNG] ?: [pb dataForType:NSPasteboardTypeTIFF];
            if (data.length > 20 * 1048576) { snapshot[@"error"] = @"Image exceeds the 20 MiB limit"; return json_string(snapshot); }
            CGImageSourceRef source = CGImageSourceCreateWithData((__bridge CFDataRef)data, NULL);
            NSDictionary *props = source ? CFBridgingRelease(CGImageSourceCopyPropertiesAtIndex(source, 0, NULL)) : nil;
            if (source) CFRelease(source);
            uint64_t width = [props[(id)kCGImagePropertyPixelWidth] unsignedLongLongValue], height = [props[(id)kCGImagePropertyPixelHeight] unsignedLongLongValue];
            if (!width || !height || width > 32000000 / height) { snapshot[@"error"] = @"Image exceeds the 32 megapixel limit"; return json_string(snapshot); }
            NSBitmapImageRep *rep = [NSBitmapImageRep imageRepWithData:data];
            NSData *png = [rep representationUsingType:NSBitmapImageFileTypePNG properties:@{}];
            if (!png) return json_string(snapshot);
            clip[@"kind"] = @"image"; clip[@"text"] = NSNull.null; clip[@"data"] = [png base64EncodedStringWithOptions:0];
        } else {
            NSString *text = [pb stringForType:NSPasteboardTypeString];
            if (!text.length) return json_string(snapshot);
            if ([text lengthOfBytesUsingEncoding:NSUTF8StringEncoding] > 1048576) { snapshot[@"error"] = @"Text exceeds the 1 MiB limit"; return json_string(snapshot); }
            clip[@"text"] = text;
            NSData *rtf = [pb dataForType:NSPasteboardTypeRTF];
            if (rtf && rtf.length <= 20 * 1048576) { clip[@"kind"] = @"rtf"; clip[@"data"] = [rtf base64EncodedStringWithOptions:0]; }
        }
        if (generation != pb.changeCount) return NULL;
        snapshot[@"clip"] = clip; return json_string(snapshot);
    }
}
bool cv_write(const char *json) {
    @autoreleasepool {
        NSDictionary *clip = [NSJSONSerialization JSONObjectWithData:[[NSString stringWithUTF8String:json] dataUsingEncoding:NSUTF8StringEncoding] options:0 error:nil];
        if (!clip) return false;
        NSString *kind = clip[@"kind"], *text = [clip[@"text"] isKindOfClass:NSString.class] ? clip[@"text"] : nil;
        NSData *data = [[NSData alloc] initWithBase64EncodedString:clip[@"data"] ?: @"" options:0];
        NSPasteboard *pb = NSPasteboard.generalPasteboard; [pb clearContents];
        BOOL result = YES;
        if ([kind isEqualToString:@"image"]) result = [pb setData:data forType:NSPasteboardTypePNG];
        else if ([kind isEqualToString:@"fileList"]) {
            NSMutableArray *urls = [NSMutableArray array];
            for (NSString *path in [text componentsSeparatedByString:@"\n"]) if (path.length) [urls addObject:[NSURL fileURLWithPath:path]];
            result = [pb writeObjects:urls];
        } else {
            if ([kind isEqualToString:@"rtf"]) result &= [pb setData:data forType:NSPasteboardTypeRTF];
            result &= [pb setString:text ?: @"" forType:NSPasteboardTypeString];
        }
        [pb setString:NSUUID.UUID.UUIDString forType:@"org.clipvault.LocalWrite"];
        owned_generation = pb.changeCount;
        return result;
    }
}
bool cv_paste(void) {
    @autoreleasepool {
        if (!AXIsProcessTrustedWithOptions((__bridge CFDictionaryRef)@{(__bridge NSString *)kAXTrustedCheckOptionPrompt:@YES})) return false;
        NSRunningApplication *previous = [NSRunningApplication runningApplicationWithProcessIdentifier:previous_app_pid];
        if (!previous) return false;
        [previous activateWithOptions:0];
        for (int i = 0; i < 20 && !previous.active; ++i) usleep(25000);
        if (!previous.active) return false;
        CGEventSourceRef source = CGEventSourceCreate(kCGEventSourceStateCombinedSessionState);
        CGEventRef down = CGEventCreateKeyboardEvent(source, 9, true), up = CGEventCreateKeyboardEvent(source, 9, false);
        if (!down || !up) { if (source) CFRelease(source); if (down) CFRelease(down); if (up) CFRelease(up); return false; }
        CGEventSetFlags(down,kCGEventFlagMaskCommand);CGEventSetFlags(up,kCGEventFlagMaskCommand);
        CGEventPost(kCGHIDEventTap,down);CGEventPost(kCGHIDEventTap,up);CFRelease(down);CFRelease(up);if (source) CFRelease(source);return true;
    }
}
char *cv_identity(void) {
    @autoreleasepool {
        NSDictionary *query = @{(__bridge id)kSecClass:(__bridge id)kSecClassGenericPassword,(__bridge id)kSecAttrService:@"com.soham.clipvault.identity",(__bridge id)kSecAttrAccount:@"noise-v1",(__bridge id)kSecReturnData:@YES};
        CFTypeRef value = NULL; OSStatus result = SecItemCopyMatching((__bridge CFDictionaryRef)query,&value);
        if (result == errSecSuccess) { NSData *data = CFBridgingRelease(value); return strdup([data base64EncodedStringWithOptions:0].UTF8String); }
        if (result != errSecItemNotFound) return NULL;
        unsigned char key[32]; if (SecRandomCopyBytes(kSecRandomDefault,32,key) != errSecSuccess) return NULL;
        NSData *data = [NSData dataWithBytes:key length:32];
        NSMutableDictionary *add = [query mutableCopy];[add removeObjectForKey:(__bridge id)kSecReturnData];add[(__bridge id)kSecValueData]=data;
        add[(__bridge id)kSecAttrAccessible]=(__bridge id)kSecAttrAccessibleAfterFirstUnlockThisDeviceOnly;
        if (SecItemAdd((__bridge CFDictionaryRef)add,NULL) != errSecSuccess) return NULL;
        return strdup([data base64EncodedStringWithOptions:0].UTF8String);
    }
}
char *cv_legacy_preferences(void) {
    @autoreleasepool {
        NSDictionary *old = [NSUserDefaults.standardUserDefaults persistentDomainForName:@"com.soham.clipvault"] ?: @{};
        NSMutableDictionary *result = [NSMutableDictionary dictionary];
        NSDictionary *keys = @{@"maxHistoryCount":@"max_history_count",@"maxDiskMegabytes":@"max_disk_megabytes",@"launchAtLogin":@"launch_at_login",@"ignorePasswordManagers":@"ignore_password_managers",@"pasteOnSelect":@"paste_on_select",@"excludedBundleIDs":@"excluded_apps"};
        for (NSString *key in keys) if (old[key]) result[keys[key]]=old[key];
        result[@"device_name"] = NSHost.currentHost.localizedName ?: @"My Mac";
        return json_string(result);
    }
